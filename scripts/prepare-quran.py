"""Render the supplied PDF faithfully; requires Poppler and cwebp on the build host.

Usage: python3 scripts/prepare-quran.py [path/to/replacement.pdf]
No Quran text or navigation mappings are generated or inferred.
"""
import concurrent.futures
import hashlib
import json
import re
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT / 'assets/quran.pdf'
if not source.is_file():
    raise SystemExit(f'PDF not found: {source}. Supply an existing PDF path.')
for command in ('pdfinfo', 'pdftoppm', 'cwebp'):
    if not shutil.which(command):
        raise SystemExit(f'Missing {command}. Install Poppler and WebP tools first.')
info = subprocess.check_output(['pdfinfo', str(source)], text=True)
count = int(re.search(r'Pages:\s+(\d+)', info)[1])
digest = hashlib.sha256(source.read_bytes()).hexdigest()
output = ROOT / 'assets/quran-pages' / digest[:12]
output.mkdir(parents=True, exist_ok=True)


def render(page):
    target = output / f'{page:03}.webp'
    # Each page is rasterized with all artwork and PDF annotations intact.
    png = subprocess.check_output([
        'pdftoppm', '-f', str(page), '-l', str(page), '-scale-to', '1800',
        '-singlefile', '-png', str(source),
    ], stderr=subprocess.DEVNULL)
    width, height = struct.unpack('>II', png[16:24])
    with tempfile.NamedTemporaryFile(suffix='.png') as image:
        image.write(png)
        image.flush()
        subprocess.run(['cwebp', '-quiet', '-q', '95', '-m', '4', image.name, '-o', str(target)],
                       check=True, stdout=subprocess.DEVNULL)
    return page, width, height


results = []
with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
    for item in pool.map(render, range(1, count + 1)):
        results.append(item)
        if item[0] % 25 == 0 or item[0] == count:
            print(f'Rendered {item[0]}/{count}', flush=True)

manifest = '// Generated by scripts/prepare-quran.py. Do not edit.\n'
manifest += f'export const PDF_SHA256 = {json.dumps(digest)};\n'
manifest += f'export const PDF_PAGE_COUNT = {count};\n'
manifest += 'export const PDF_PAGES = [\n'
for page, width, height in results:
    path = f'../../assets/quran-pages/{digest[:12]}/{page:03}.webp'
    manifest += f'  {{ page: {page}, source: require({json.dumps(path)}), width: {width}, height: {height} }},\n'
manifest += '];\n'
with tempfile.NamedTemporaryFile(mode='w', dir=ROOT / 'src/data', delete=False) as file:
    file.write(manifest)
    temporary = Path(file.name)
temporary.replace(ROOT / 'src/data/pdf-pages.ts')
(ROOT / 'src/data/pdf-document.json').write_text(json.dumps({
    'sha256': digest, 'pageCount': count, 'longEdge': 1800, 'format': 'webp', 'quality': 95,
}, indent=2) + '\n')
print(f'Prepared {count} PDF pages. SHA-256: {digest}', flush=True)
